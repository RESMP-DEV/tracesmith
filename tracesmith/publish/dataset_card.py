"""Auto-generate a HF Hub dataset card from MANIFEST.json."""
from __future__ import annotations

import json


def render_card(manifest: dict, repo_id: str, license_name: str = "mit") -> str:
    sources = manifest.get("sources", {})
    src_lines = "\n".join(
        f"| {name} | {s.get('raw_records', 0)} | "
        f"{s.get('exported_messages', 0)} | {s.get('exported_sharegpt_pairs', 0)} |"
        for name, s in sorted(sources.items())
    )
    export_summary = manifest.get("export_summary", {})
    total_msgs = export_summary.get("messages_rows", 0)
    total_pairs = export_summary.get("sharegpt_pairs", 0)
    return f"""---
license: {license_name}
task_categories:
  - text-generation
language:
  - en
tags:
  - code
  - distillation
  - agent-traces
size_categories:
  - 1K<n<10K
---

# {repo_id}

Generated by [TraceSmith](https://github.com/resmp-dev/tracesmith).

## Contents

DistillKit-ready coding-agent traces in two variants:
- `messages.jsonl`: multi-turn chat (`messages` column, OpenAI chat format)
- `sharegpt.jsonl`: instruction pairs (`conversations` column, ShareGPT format)

Each row includes TraceSmith metadata schema version
`{manifest.get('metadata_schema_version', 'unknown')}` for source, project,
model, lifecycle, structure, tool, diff, and message-level filtering.

## Source breakdown

| Source | Raw records | Conversations | ShareGPT pairs |
|---|---:|---:|---:|
{src_lines}

**Totals:** {total_msgs} conversations / {total_pairs} instruction pairs.

## Redaction

All traces were processed through TraceSmith's redaction pipeline:
{json.dumps(manifest.get('config', {}), indent=2)}

Inspect a sample before using. See the project README for the full methodology.
"""
