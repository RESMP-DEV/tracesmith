"""Auto-generate a HF Hub dataset card from MANIFEST.json."""
from __future__ import annotations

import json
from pathlib import Path


def render_card(manifest: dict, repo_id: str, license_name: str = "mit") -> str:
    sources = manifest.get("sources", {})
    src_lines = "\n".join(
        f"| {name} | {s.get('exported_messages', 0)} | {s.get('exported_sharegpt_pairs', 0)} |"
        for name, s in sorted(sources.items())
    )
    total_msgs = sum(s.get("exported_messages", 0) for s in sources.values())
    total_pairs = sum(s.get("exported_sharegpt_pairs", 0) for s in sources.values())
    return f"""---
license: {license_name}
task_categories:
  - text-generation
language:
  - en
tags:
  - code
  - distillation
  - agent-traces
size_categories:
  - 1K<n<10K
---

# {repo_id}

Generated by [agent-trace-share](https://github.com/your-org/agent-trace-share).

## Contents

DistillKit-ready coding-agent traces in two variants:
- `messages.jsonl`: multi-turn chat (`messages` column, OpenAI chat format)
- `sharegpt.jsonl`: instruction pairs (`conversations` column, ShareGPT format)

## Source breakdown

| Source | Conversations | ShareGPT pairs |
|---|---|---|
{src_lines}

**Totals:** {total_msgs} conversations / {total_pairs} instruction pairs.

## Redaction

All traces were processed through agent-trace-share's redaction pipeline:
{json.dumps(manifest.get('config', {}), indent=2)}

Inspect a sample before using. See the project README for the full methodology.
"""
